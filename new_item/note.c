/*
git status

添加， U标志，未跟踪
修改， M标志，修改
删除，文件删除，无其他变化


pwd显示当前ps所在文件夹位置
cd.. 返回上一级目录
cd .\文件名 进入下一级文件夹 cd 和. 间有空格
ls 显示当前文件夹所有文件
按住alt+鼠标左键可以多出一个光标，便于批量修改
选中某个东西按ctrl+D，可以同时选中下一个相同的东西
按住alt+shift，把上一行的内容复制到下一行 （原来的下一行下移）
ctrl+f查找
git add . 把当前文件夹下的所有文件加入暂存区
git commit 提交
注意：会产生一个vim编辑器
先输入i,进入到插入模式，这是输入描述
输入完毕后按Esc退出，按下英文键:wq表示输入完毕
按下Enter即可
git log 显示提交日志
git commit --m "提交说明"
这种方式不用vim编辑，方便
git commit --m "fix(note): change content"
规范表示
*/